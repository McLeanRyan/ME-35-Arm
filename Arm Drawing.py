led = Pin(16, Pin.OUT)

def angle_to_ns(theta):
    theta = min(theta, 180)
    theta = max(0, theta)
    duty_us = 500 + 2000*(theta/180)
    duty_ns = int(1000*duty_us)
    
    return duty_ns

def draw_fish(delay):
    for i in range(len(THETA1)):
        servo_1.duty_ns(angle_to_ns(THETA1[i]))
        servo_2.duty_ns(angle_to_ns(THETA2[i]))
        time.sleep_ms(delay)
    
    return
    
    

